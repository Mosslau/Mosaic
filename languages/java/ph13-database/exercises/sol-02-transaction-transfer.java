// 要点：
//   - 事务边界由业务定义：setAutoCommit(false) 到 commit() 之间就是「一次转账」
//   - 余额不足用 SQL 条件 WHERE balance_cents >= ? 守底线（影响 0 行），而不是先 SELECT 再判断
