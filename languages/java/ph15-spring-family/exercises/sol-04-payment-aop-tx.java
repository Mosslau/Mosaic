package com.example.pay;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.test.context.ContextConfiguration;
import org.springframework.test.context.junit.jupiter.SpringExtension;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/**
 * sol-04 测试：支付成功扣款 + 审计落库；余额不足 → 业务异常回滚（无任何副作用）；
 * 切面计数验证代理生效。
 * 验证命令：mvn -o -Dmaven.repo.local=/tmp/m2clone test
 */
@ExtendWith(SpringExtension.class)
@ContextConfiguration(classes = PayTxConfig.class)
class PaymentTxTest {

    @Autowired
    private PaymentService paymentService;

    @Autowired
    private PaymentAuditAspect aspect;

    @Test
    void payDeductsAndAuditsInSeparateTransaction() {
        paymentService.openWallet("wallet-a", 100);
        paymentService.pay("wallet-a", "ORD-001", 30);
        assertThat(paymentService.balanceOf("wallet-a")).isEqualTo(70);
        assertThat(paymentService.auditCount("ORD-001")).isEqualTo(1);
    }

    /** 余额不足：业务异常（运行时）→ 主事务回滚，且 REQUIRES_NEW 审计也不该产生 */
    @Test
    void insufficientBalanceRollsBackWithoutSideEffects() {
        paymentService.openWallet("wallet-b", 10);
        assertThatThrownBy(() -> paymentService.pay("wallet-b", "ORD-002", 50))
                .isInstanceOf(PaymentService.InsufficientBalanceException.class);
        assertThat(paymentService.balanceOf("wallet-b")).isEqualTo(10);   // 扣款没发生
        assertThat(paymentService.auditCount("ORD-002")).isEqualTo(0);    // 审计在异常前根本没执行
    }

    /** 切面计数：每次经代理的 pay 调用 +1 */
    @Test
    void aspectCountsProxiedPayCalls() {
        paymentService.openWallet("wallet-c", 100);
        long before = aspect.payCallCount();
        paymentService.pay("wallet-c", "ORD-003", 5);
        assertThat(aspect.payCallCount()).isEqualTo(before + 1);
    }
}

