package com.example.pay;

import org.aspectj.lang.ProceedingJoinPoint;
import org.aspectj.lang.annotation.Around;
import org.aspectj.lang.annotation.Aspect;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Component;

import java.util.concurrent.atomic.AtomicInteger;

/** 支付耗时切面：@Around 记录每个经过代理的支付调用（配合事务代理同源机制） */
@Aspect
@Component
public class PaymentAuditAspect {

    private static final Logger log = LoggerFactory.getLogger(PaymentAuditAspect.class);
    private final AtomicInteger proxiedCalls = new AtomicInteger();

    @Around("execution(* com.example.pay.PaymentService.pay(..))")
    public Object timePay(ProceedingJoinPoint pjp) throws Throwable {
        proxiedCalls.incrementAndGet();
        long start = System.nanoTime();
        try {
            Object result = pjp.proceed();
            log.info("pay 成功，耗时 {} ms", (System.nanoTime() - start) / 1_000_000);
            return result;
        } catch (Throwable t) {
            log.warn("pay 失败：{}", t.getMessage());
            throw t;
        }
    }

    public int payCallCount() {
        return proxiedCalls.get();
    }
}

