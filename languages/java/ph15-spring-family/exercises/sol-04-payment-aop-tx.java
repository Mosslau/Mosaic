package com.example.pay;

import org.springframework.beans.factory.ObjectProvider;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Propagation;
import org.springframework.transaction.annotation.Transactional;

/**
 * 支付服务：业务失败抛「业务异常」回滚扣款；审计流水 REQUIRES_NEW 独立落库；
 * 被拒支付（余额不足）抛出后外层不产生任何副作用——练习要求把「回滚规则」讲清楚。
 */
@Service
public class PaymentService {

    private final JdbcTemplate jdbc;
    private final ObjectProvider<PaymentService> self;

    public PaymentService(JdbcTemplate jdbc, ObjectProvider<PaymentService> self) {
        this.jdbc = jdbc;
        this.self = self;
    }

    public PaymentService proxiedSelf() {
        return self.getObject();
    }

    @Transactional
    public void openWallet(String name, int balance) {
        jdbc.update("INSERT INTO wallets(name, balance) VALUES (?, ?)", name, balance);
    }

    /** 支付：扣款 + 审计流水（REQUIRES_NEW）+ 余额不足抛业务异常（运行时 → 默认回滚） */
    @Transactional
    public void pay(String wallet, String orderNo, int amount) {
        int balance = balanceOf(wallet);
        if (balance < amount) {
            throw new InsufficientBalanceException("余额不足：需要 " + amount + "，当前 " + balance);
        }
        jdbc.update("UPDATE wallets SET balance = balance - ? WHERE name = ?", amount, wallet);
        proxiedSelf().audit(orderNo, amount); // REQUIRES_NEW：审计独立提交，主事务失败它也在
    }

    @Transactional(propagation = Propagation.REQUIRES_NEW)
    public void audit(String orderNo, int amount) {
        jdbc.update("INSERT INTO pay_audit(order_no, amount) VALUES (?, ?)", orderNo, amount);
    }

    @Transactional(readOnly = true)
    public int balanceOf(String name) {
        Integer b = jdbc.queryForObject("SELECT balance FROM wallets WHERE name = ?", Integer.class, name);
        return b == null ? -1 : b;
    }

    public int auditCount(String orderPrefix) {
        Integer n = jdbc.queryForObject(
                "SELECT COUNT(*) FROM pay_audit WHERE order_no LIKE ?", Integer.class, orderPrefix + "%");
        return n == null ? 0 : n;
    }

    /** 业务异常（运行时）：触发 @Transactional 默认回滚规则 */
    public static final class InsufficientBalanceException extends IllegalStateException {
        public InsufficientBalanceException(String message) {
            super(message);
        }
    }
}

